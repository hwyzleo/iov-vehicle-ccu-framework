#!/bin/bash
#
# stage-yaml-cpp.sh - 将 third_party 中的 HOST 预编译 yaml-cpp 受控 staging 为
# 标准 CMake package 前缀（CGW-FW-DSN-CR-006 §6）。
#
# 产出布局（${CGW_DEP_STAGING}/usr）：
#   include/yaml-cpp/**          公共头文件
#   lib/libyaml-cpp.a            目标架构静态库
#   lib/cmake/yaml-cpp/
#       yaml-cppConfig.cmake     可重定位 package config
#       yaml-cppConfigVersion.cmake
#       yaml-cppTargets.cmake    IMPORTED STATIC target yaml-cpp::yaml-cpp
#
# 约束：
#   - 本脚本仅用于 HOST 开发/测试，产出的 archive 是 HOST 架构预编译制品，
#     不得用于 aarch64-linux 目标链接；目标构建由 BUILD 受控 recipe 替换。
#   - 不再使用 if(EXISTS <arch-path>) 静默 fallback；缺失时 fail-closed。
#
# 用法:
#   scripts/stage-yaml-cpp.sh                       # stage 到 ${CGW_DEP_STAGING}
#   CGW_DEP_STAGING=/tmp/deps scripts/stage-yaml-cpp.sh
#
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"

# 构建环境单一来源
source "${SCRIPT_DIR}/cgw-env.sh"

: "${CGW_DEP_STAGING:?CGW_DEP_STAGING 未设置}"

# ---- 1. 探测 HOST 架构预编译制品路径 ----
detect_arch_dir() {
    local proc="${CMAKE_SYSTEM_PROCESSOR:-$(uname -m)}"
    # 允许通过环境覆盖
    if [[ -n "${CGW_FW_HOST_ARCH_DIR:-}" ]]; then
        echo "${PROJECT_ROOT}/third_party/lib/${CGW_FW_HOST_ARCH_DIR}"
        return
    fi
    case "$(uname -s)" in
        Darwin)
            case "$(uname -m)" in
                arm64|aarch64) echo "${PROJECT_ROOT}/third_party/lib/arm64-apple-darwin" ;;
                x86_64)        echo "${PROJECT_ROOT}/third_party/lib/x86_64-apple-darwin" ;;
                *) return 1 ;;
            esac ;;
        Linux)
            case "$(uname -m)" in
                aarch64|arm64) echo "${PROJECT_ROOT}/third_party/lib/aarch64-linux-gnu" ;;
                x86_64)        echo "${PROJECT_ROOT}/third_party/lib/x86_64-linux-gnu" ;;
                *) return 1 ;;
            esac ;;
        *) return 1 ;;
    esac
}

ARCH_DIR="$(detect_arch_dir || true)"
ARCHIVE="${ARCH_DIR:-}/yaml-cpp/libyaml-cpp.a"
HEADERS="${PROJECT_ROOT}/third_party/include/yaml-cpp"

if [[ -z "${ARCH_DIR}" || ! -f "${ARCHIVE}" ]]; then
    echo "[stage-yaml-cpp] FAIL: 未找到当前 HOST 架构的预编译 yaml-cpp 归档。" >&2
    echo "[stage-yaml-cpp]   期望路径: ${ARCHIVE:-<unset>}" >&2
    echo "[stage-yaml-cpp]   目标平台构建应由 BUILD 受控 recipe 提供匹配架构的 yaml-cpp package。" >&2
    exit 1
fi
if [[ ! -d "${HEADERS}" ]]; then
    echo "[stage-yaml-cpp] FAIL: 未找到 yaml-cpp 公共头文件: ${HEADERS}" >&2
    exit 1
fi

# ---- 2. staging ----
STAGING_USR="${CGW_DEP_STAGING}/usr"
STAGING_INCLUDE="${STAGING_USR}/include"
STAGING_LIB="${STAGING_USR}/lib"
STAGING_CMAKE="${STAGING_LIB}/cmake/yaml-cpp"

echo "[stage-yaml-cpp] staging -> ${STAGING_USR}"
rm -rf "${STAGING_USR}"
mkdir -p "${STAGING_INCLUDE}" "${STAGING_LIB}" "${STAGING_CMAKE}"

cp -R "${HEADERS}" "${STAGING_INCLUDE}/yaml-cpp"
cp "${ARCHIVE}" "${STAGING_LIB}/libyaml-cpp.a"

# ---- 3. 生成可重定位 CMake package 文件 ----
cat > "${STAGING_CMAKE}/yaml-cppTargets.cmake" <<'EOF'
# Generated by scripts/stage-yaml-cpp.sh (CR-006 §6). Do not edit by hand.
# Provides IMPORTED STATIC target yaml-cpp::yaml-cpp from a controlled prefix.

# Guard against double-include.
if(TARGET yaml-cpp::yaml-cpp)
    return()
endif()

# Derive the staging prefix from this file's own location (relocatable):
#   <prefix>/lib/cmake/yaml-cpp/yaml-cppTargets.cmake -> <prefix>
get_filename_component(_IMPORT_PREFIX "${CMAKE_CURRENT_LIST_DIR}/../../.." ABSOLUTE)

add_library(yaml-cpp::yaml-cpp STATIC IMPORTED)
set_target_properties(yaml-cpp::yaml-cpp PROPERTIES
    IMPORTED_LOCATION "${_IMPORT_PREFIX}/lib/libyaml-cpp.a"
    INTERFACE_INCLUDE_DIRECTORIES "${_IMPORT_PREFIX}/include"
)

unset(_IMPORT_PREFIX)
EOF

cat > "${STAGING_CMAKE}/yaml-cppConfig.cmake" <<'EOF'
# yaml-cppConfig.cmake - controlled staging (HOST) package config (CR-006 §6).
# find_package(yaml-cpp CONFIG REQUIRED) resolves this and the imported target.
get_filename_component(_SELF_DIR "${CMAKE_CURRENT_LIST_DIR}" ABSOLUTE)
include("${_SELF_DIR}/yaml-cppTargets.cmake")
set(yaml-cpp_FOUND TRUE)
unset(_SELF_DIR)
EOF

# Minimal permissive version file (no version constraint is requested by CGW-FW).
cat > "${STAGING_CMAKE}/yaml-cppConfigVersion.cmake" <<'EOF'
# yaml-cppConfigVersion.cmake - controlled staging (HOST).
set(PACKAGE_VERSION "0.0.0-host")
set(PACKAGE_VERSION_EXACT FALSE)
set(PACKAGE_VERSION_COMPATIBLE TRUE)
set(PACKAGE_VERSION_UNSUITABLE FALSE)
EOF

echo "[stage-yaml-cpp] OK"
echo "[stage-yaml-cpp]   target:      yaml-cpp::yaml-cpp (STATIC IMPORTED)"
echo "[stage-yaml-cpp]   archive:     ${STAGING_LIB}/libyaml-cpp.a"
echo "[stage-yaml-cpp]   cmake root:  ${STAGING_CMAKE}"
echo "[stage-yaml-cpp] 消费方请设置 CMAKE_PREFIX_PATH=${STAGING_USR}"
